//! OSCAL 1.2.3 Catalog (JSON or XML) -> OGRL library (`framework`, `requirement`, draft `mapping`).
//!
//! Full parity with Go `internal/oscalimport`, plus RFC 0001 §7.2 assessment `objectives`
//! and `methods` extraction from OSCAL `assessment-objective` / `assessment-method` parts.

use std::collections::{BTreeMap, HashMap, HashSet};
use std::fs;
use std::path::Path;
use std::sync::LazyLock;

use chrono::{DateTime, Utc};
use regex::Regex;
use serde::Deserialize;
use serde_json::Value;
use thiserror::Error;

use ogrl_core::bundle::BundleManifest;
use ogrl_core::model::{
    AssessmentMethod, AssessmentMethodKind, Confidence, ExternalReference, Framework, Mapping,
    Objective, OgrlObject, Parameter, Rationale, Relationship, Reproduction, Requirement,
    RequirementClass, RequirementPart, ReviewStatus, SPEC_VERSION,
};
use ogrl_core::time::{format_timestamp, parse_timestamp};
use ogrl_core::yaml;

use crate::xml::{looks_like_xml, oscal_xml_to_json};

pub const GENERATED_COMMENT: &str =
    "Generated by `ogrl import` from an OSCAL catalog. Do not edit.";

static INSERT_RE: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"\{\{\s*insert:\s*param,\s*([^}\s]+)\s*\}\}").unwrap());
static CONTROL_REF_RE: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"^[A-Z]{2}-\d{2}(?:\(\d{2}\))?$").unwrap());
static CONTROL_DISPLAY_RE: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"^[A-Z]{2}-\d+(\(\d+\))?$").unwrap());
static PART_HREF_RE: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"^#([a-z0-9][a-z0-9.-]*)_smt\.([a-z0-9.]+)$").unwrap());
static HASH_HREF_RE: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"^#([a-z0-9][a-z0-9.-]*)$").unwrap());

#[derive(Debug, Error)]
pub enum CatalogError {
    #[error("framework_id is required")]
    MissingFrameworkId,
    #[error("parse OSCAL catalog: {0}")]
    Parse(String),
    #[error("catalog metadata last-modified is empty or invalid: {0}")]
    Timestamp(String),
    #[error("unresolved reference: {0}")]
    UnresolvedRef(String),
    #[error("duplicate mapping id {0}")]
    DuplicateMapping(String),
    #[error("I/O error: {0}")]
    Io(#[from] std::io::Error),
}

#[derive(Debug, Clone)]
pub struct ImportOptions {
    pub framework_id: String,
    pub name: Option<String>,
    pub publisher: String,
    pub source_uri: Option<String>,
    pub source_path: Option<String>,
    pub commit: Option<String>,
    pub version: Option<String>,
}

impl Default for ImportOptions {
    fn default() -> Self {
        Self {
            framework_id: String::new(),
            name: None,
            publisher: "NIST".into(),
            source_uri: None,
            source_path: None,
            commit: None,
            version: None,
        }
    }
}

#[derive(Debug, Clone)]
struct IndexRef {
    id: String,
    parts: HashSet<String>,
}

/// Resolves OSCAL control identifiers to OGRL requirement IDs across catalogs.
#[derive(Debug, Clone)]
pub struct CatalogIndex {
    pub framework_id: String,
    by_oscal_id: HashMap<String, IndexRef>,
    by_sort_id: HashMap<String, IndexRef>,
    by_zero_padded: HashMap<String, IndexRef>,
}

#[derive(Debug, Clone)]
pub struct CatalogImportOutput {
    pub framework_id: String,
    pub framework: Framework,
    pub requirements: Vec<(String, Requirement)>, // (local_slug, Requirement)
    pub mappings: Vec<Mapping>,
    pub modified: DateTime<Utc>,
    pub withdrawn_count: usize,
    pub objectives_count: usize,
    pub index: CatalogIndex,
}

