/// Build an index of an OSCAL catalog without emitting files (for `--resolve-catalog`).
pub fn index_only(doc_bytes: &[u8], framework_id: &str) -> Result<CatalogIndex, CatalogError> {
    let out = import_catalog_bytes(
        doc_bytes,
        &ImportOptions {
            framework_id: framework_id.to_string(),
            ..Default::default()
        },
        None,
    )?;
    Ok(out.index)
}

/// Parse an OSCAL 1.2.3 catalog (JSON or XML) into OGRL objects in memory.
pub fn import_catalog_bytes(
    doc_bytes: &[u8],
    opt: &ImportOptions,
    resolve: Option<&CatalogIndex>,
) -> Result<CatalogImportOutput, CatalogError> {
    if opt.framework_id.is_empty() {
        return Err(CatalogError::MissingFrameworkId);
    }
    let publisher = if opt.publisher.is_empty() {
        "NIST".to_string()
    } else {
        opt.publisher.clone()
    };

    let parsed: CatalogDoc = if looks_like_xml(doc_bytes) {
        let val = oscal_xml_to_json(doc_bytes).map_err(|e| CatalogError::Parse(e.to_string()))?;
        serde_json::from_value(val).map_err(|e| CatalogError::Parse(e.to_string()))?
    } else {
        serde_json::from_slice(doc_bytes).map_err(|e| CatalogError::Parse(e.to_string()))?
    };

    let cat = parsed.catalog;
    if cat.metadata.last_modified.is_empty() {
        return Err(CatalogError::Timestamp("empty".into()));
    }
    let stamp = parse_timestamp(&cat.metadata.last_modified)
        .map_err(|e| CatalogError::Timestamp(e.to_string()))?;
    let name = opt
        .name
        .clone()
        .filter(|s| !s.is_empty())
        .unwrap_or_else(|| cat.metadata.title.clone());
    let version = opt
        .version
        .clone()
        .filter(|s| !s.is_empty())
        .unwrap_or_else(|| cat.metadata.version.clone());

    let mut resources: HashMap<&str, &OscalResource> = HashMap::new();
    for r in &cat.back_matter.resources {
        resources.insert(r.uuid.as_str(), r);
    }

    let mut families: HashMap<String, String> = HashMap::new();
    let mut collected: Vec<CollectedReq> = Vec::new();

    for c in &cat.controls {
        collect_control(
            &mut collected,
            c,
            &opt.framework_id,
            &publisher,
            stamp,
            &[],
            &resources,
            resolve,
        );
    }
    for g in &cat.groups {
        collect_group(
            &mut collected,
            &mut families,
            g,
            &opt.framework_id,
            &publisher,
            stamp,
            &resources,
            resolve,
        );
    }

    let self_idx = build_index(&opt.framework_id, &collected);

    let mut mappings = Vec::new();
    let mut seen_map_ids = HashSet::new();
    for item in &mut collected {
        let (got, extra) = mappings_for(item, &self_idx, resolve, &resources, &families)?;
        if !extra.is_empty() {
            item.req
                .external_references
                .get_or_insert_with(Vec::new)
                .extend(extra);
        }
        for m in got {
            if !seen_map_ids.insert(m.id.clone()) {
                return Err(CatalogError::DuplicateMapping(m.id));
            }
            mappings.push(m);
        }
    }

    let mut source_map = BTreeMap::new();
    source_map.insert("format".into(), Value::String("oscal-catalog".into()));
    if let Some(u) = &opt.source_uri {
        if !u.is_empty() {
            source_map.insert("uri".into(), Value::String(u.clone()));
        }
    }
    if let Some(p) = &opt.source_path {
        if !p.is_empty() {
            source_map.insert("path".into(), Value::String(p.clone()));
        }
    }
    if let Some(c) = &opt.commit {
        if !c.is_empty() {
            source_map.insert("commit".into(), Value::String(c.clone()));
        }
    }

    let framework = Framework {
        object_type: "framework".into(),
        id: format!("framework--{}", opt.framework_id),
        spec_version: SPEC_VERSION.into(),
        created: stamp,
        modified: stamp,
        name,
        revoked: None,
        created_by_ref: None,
        tags: None,
        external_references: None,
        extensions: None,
        lang: None,
        publisher,
        version,
        reproduction: Reproduction::Permitted,
        source: Some(source_map),
        extra: BTreeMap::new(),
    };

    let withdrawn_count = collected.iter().filter(|c| c.req.is_withdrawn()).count();
    let objectives_count = collected
        .iter()
        .map(|c| c.req.objectives.as_deref().map_or(0, <[Objective]>::len))
        .sum();
    let requirements = collected
        .into_iter()
        .map(|c| (c.local_slug, c.req))
        .collect();

    Ok(CatalogImportOutput {
        framework_id: opt.framework_id.clone(),
        framework,
        requirements,
        mappings,
        modified: stamp,
        withdrawn_count,
        objectives_count,
        index: self_idx,
    })
}

/// Write a `CatalogImportOutput` into a repository-form library directory (`framework/`,
/// `requirement/<framework_id>/`, `mapping/`), replacing prior files owned by that framework.
pub fn write_library_output(
    out_dir: &Path,
    output: &CatalogImportOutput,
) -> Result<(), CatalogError> {
    let fw_dir = out_dir.join("framework");
    let req_dir = out_dir.join("requirement").join(&output.framework_id);
    let map_dir = out_dir.join("mapping");

    if req_dir.exists() {
        fs::remove_dir_all(&req_dir)?;
    }
    fs::create_dir_all(&fw_dir)?;
    fs::create_dir_all(&req_dir)?;
    fs::create_dir_all(&map_dir)?;

    remove_owned_mappings(&map_dir, &output.framework_id)?;

    let fw_val = OgrlObject::Framework(output.framework.clone()).to_json_value();
    fs::write(
        fw_dir.join(format!("{}.yaml", output.framework_id)),
        yaml::format_yaml(&fw_val, Some(GENERATED_COMMENT)),
    )?;

    for (local_slug, req) in &output.requirements {
        let val = OgrlObject::Requirement(req.clone()).to_json_value();
        fs::write(
            req_dir.join(format!("{local_slug}.yaml")),
            yaml::format_yaml(&val, Some(GENERATED_COMMENT)),
        )?;
    }

    for m in &output.mappings {
        let filename = format!("{}.yaml", m.id.trim_start_matches("mapping--"));
        let val = OgrlObject::Mapping(m.clone()).to_json_value();
        fs::write(
            map_dir.join(filename),
            yaml::format_yaml(&val, Some(GENERATED_COMMENT)),
        )?;
    }
    Ok(())
}

/// Write `bundle.yaml` for the standard library. An existing manifest is left untouched so
/// regenerating catalogs into a released library never resets its version or name.
pub fn write_library_bundle(
    out_dir: &Path,
    created: DateTime<Utc>,
    modified: DateTime<Utc>,
) -> Result<(), CatalogError> {
    fs::create_dir_all(out_dir)?;
    if out_dir.join("bundle.yaml").exists() {
        return Ok(());
    }
    let manifest = BundleManifest {
        object_type: "bundle".into(),
        id: "bundle--ogrl-library".into(),
        spec_version: SPEC_VERSION.into(),
        created: Some(format_timestamp(&created)),
        modified: Some(format_timestamp(&modified)),
        name: Some("OGRL Control Library".into()),
        version: Some("0.1.0".into()),
        library: None,
        providers: None,
        extra: BTreeMap::new(),
    };
    let val = serde_json::to_value(&manifest).unwrap();
    fs::write(
        out_dir.join("bundle.yaml"),
        yaml::format_yaml(&val, Some(GENERATED_COMMENT)),
    )?;
    Ok(())
}

fn remove_owned_mappings(dir: &Path, framework_id: &str) -> Result<(), CatalogError> {
    if !dir.exists() {
        return Ok(());
    }
    let prefix = format!("{framework_id}-");
    for entry in fs::read_dir(dir)? {
        let entry = entry?;
        if entry.file_type()?.is_dir() {
            continue;
        }
        let name = entry.file_name();
        let name = name.to_string_lossy();
        if name.starts_with(&prefix) && name.ends_with(".yaml") {
            fs::remove_file(entry.path())?;
        }
    }
    Ok(())
}

#[allow(clippy::too_many_arguments)]
fn collect_group(
    dst: &mut Vec<CollectedReq>,
    families: &mut HashMap<String, String>,
    g: &OscalGroup,
    framework_id: &str,
    publisher: &str,
    stamp: DateTime<Utc>,
    resources: &HashMap<&str, &OscalResource>,
    resolve: Option<&CatalogIndex>,
) {
    if !g.id.is_empty() {
        families.insert(g.id.clone(), g.title.clone());
    }
    for c in &g.controls {
        collect_control(
            dst,
            c,
            framework_id,
            publisher,
            stamp,
            &[],
            resources,
            resolve,
        );
    }
    for sub in &g.groups {
        collect_group(
            dst,
            families,
            sub,
            framework_id,
            publisher,
            stamp,
            resources,
            resolve,
        );
    }
}

#[allow(clippy::too_many_arguments)]
fn collect_control(
    dst: &mut Vec<CollectedReq>,
    c: &OscalControl,
    framework_id: &str,
    publisher: &str,
    stamp: DateTime<Utc>,
    inherited: &[TokenParam],
    resources: &HashMap<&str, &OscalResource>,
    resolve: Option<&CatalogIndex>,
) {
    let (mut local_params, mut by_token) = params_of(&c.params);
    let sort_id = prop_value(&c.props, "sort-id", "");
    let display = display_id(&c.props, &sort_id, &c.id);
    let mut local_slug = slug(&c.id);
    if !sort_id.is_empty() && (c.id.contains("800_171") || sort_id.starts_with('0')) {
        local_slug = slug(&sort_id);
    }
    let class = if c.class == "SP800-53-enhancement" {
        RequirementClass::Enhancement
    } else {
        RequirementClass::Control
    };
    let withdrawn = prop_value(&c.props, "status", "") == "withdrawn";
    let mut name = c.title.trim().to_string();
    if name.is_empty() {
        name = display.clone();
    }

    let mut used_inherited: HashSet<String> = HashSet::new();
    let mut rewrite = |prose: &str| -> String {
        INSERT_RE
            .replace_all(prose, |caps: &regex::Captures<'_>| {
                let tok = caps[1].trim();
                if let Some(key) = by_token.get(tok) {
                    return format!("{{{{ {key} }}}}");
                }
                if let Some(p) = inherited.iter().find(|p| p.token == tok) {
                    if used_inherited.insert(p.key.clone()) {
                        local_params.insert(
                            p.key.clone(),
                            Parameter {
                                label: Some(p.label.clone()),
                                value: None,
                                extra: BTreeMap::new(),
                            },
                        );
                    }
                    return format!("{{{{ {} }}}}", p.key);
                }
                let key = param_key(tok);
                if !by_token.contains_key(&key) {
                    local_params.insert(
                        key.clone(),
                        Parameter {
                            label: Some(tok.to_string()),
                            value: None,
                            extra: BTreeMap::new(),
                        },
                    );
                    by_token.insert(tok.to_string(), key.clone());
                    by_token.insert(key.clone(), key.clone());
                }
                format!("{{{{ {} }}}}", by_token[tok])
            })
            .into_owned()
    };

    let mut statement = None;
    let mut parts = Vec::new();
    if let Some(stmt) = c.parts.iter().find(|p| p.name == "statement") {
        if !stmt.prose.trim().is_empty() {
            statement = Some(rewrite(stmt.prose.trim()));
        }
        flatten_parts(&stmt.parts, &[], &sort_id, &mut rewrite, &mut parts);
    }

    // Extract assessment objectives and methods (RFC 0001 §7.2).
    let methods = extract_assessment_methods(&c.parts, &mut rewrite);
    let mut objectives = Vec::new();
    for p in &c.parts {
        if p.name == "assessment-objective" {
            flatten_objectives(
                p,
                &c.id,
                &sort_id,
                &[],
                &methods,
                &mut rewrite,
                &mut objectives,
            );
        }
    }

    let ext = citations(&c.links, resources, publisher, resolve);
    let req_id = format!("requirement--{framework_id}-{local_slug}");
    let req = Requirement {
        object_type: "requirement".into(),
        id: req_id,
        spec_version: SPEC_VERSION.into(),
        created: stamp,
        modified: stamp,
        name,
        revoked: None,
        created_by_ref: None,
        tags: None,
        external_references: if ext.is_empty() { None } else { Some(ext) },
        extensions: None,
        lang: None,
        framework_ref: format!("framework--{framework_id}"),
        class,
        display_id: Some(display),
        withdrawn: if withdrawn { Some(true) } else { None },
        statement,
        citation: None,
        parameters: if local_params.is_empty() {
            None
        } else {
            Some(local_params)
        },
        parts: if parts.is_empty() { None } else { Some(parts) },
        objectives: if objectives.is_empty() {
            None
        } else {
            Some(objectives)
        },
        extra: BTreeMap::new(),
    };

    let zero_pad = prop_value(&c.props, "label", "zero-padded");
    dst.push(CollectedReq {
        req,
        local_slug,
        oscal_id: c.id.clone(),
        sort_id,
        zero_pad,
        links: c.links.clone(),
    });

    let next_inherited = inherit_params(&c.params, &by_token);
    for child in &c.controls {
        collect_control(
            dst,
            child,
            framework_id,
            publisher,
            stamp,
            &next_inherited,
            resources,
            resolve,
        );
    }
}

fn extract_assessment_methods<F: FnMut(&str) -> String>(
    parts: &[OscalPart],
    rewrite: &mut F,
) -> Vec<AssessmentMethod> {
    let mut out = Vec::new();
    for p in parts {
        if p.name != "assessment-method" {
            continue;
        }
        let kind_str = prop_value(&p.props, "method", "").to_ascii_lowercase();
        let kind = match kind_str.as_str() {
            "examine" => AssessmentMethodKind::Examine,
            "interview" => AssessmentMethodKind::Interview,
            "test" => AssessmentMethodKind::Test,
            _ => continue,
        };
        let mut statements: Vec<String> = Vec::new();
        if !p.prose.trim().is_empty() {
            statements.push(normalize_method_prose(&rewrite(p.prose.trim())));
        }
        for sub in &p.parts {
            if !sub.prose.trim().is_empty() {
                statements.push(normalize_method_prose(&rewrite(sub.prose.trim())));
            }
        }
        let stmt = if statements.is_empty() {
            None
        } else {
            Some(statements.join("; "))
        };
        out.push(AssessmentMethod {
            method: kind,
            statement: stmt,
            extra: BTreeMap::new(),
        });
    }
    out
}

fn normalize_method_prose(text: &str) -> String {
    text.split('\n')
        .map(str::trim)
        .filter(|line| !line.is_empty())
        .collect::<Vec<_>>()
        .join("; ")
}

fn flatten_objectives<F: FnMut(&str) -> String>(
    part: &OscalPart,
    oscal_id: &str,
    sort_id: &str,
    chain: &[String],
    methods: &[AssessmentMethod],
    rewrite: &mut F,
    out: &mut Vec<Objective>,
) {
    let sub_objs: Vec<&OscalPart> = part
        .parts
        .iter()
        .filter(|p| p.name == "assessment-objective")
        .collect();

    let id = objective_local_id(part, oscal_id, sort_id, chain);
    let prose = rewrite(part.prose.trim());

    if sub_objs.is_empty() {
        if !prose.is_empty() {
            let final_id = if id.is_empty() { "obj".to_string() } else { id };
            out.push(Objective {
                id: final_id,
                statement: prose,
                methods: if methods.is_empty() {
                    None
                } else {
                    Some(methods.to_vec())
                },
                extra: BTreeMap::new(),
            });
        }
        return;
    }

    let mut next_chain = chain.to_vec();
    if !id.is_empty() {
        next_chain.push(id);
    }
    for sub in sub_objs {
        flatten_objectives(sub, oscal_id, sort_id, &next_chain, methods, rewrite, out);
    }
}

fn objective_local_id(part: &OscalPart, oscal_id: &str, sort_id: &str, chain: &[String]) -> String {
    // 1. SP 800-53 style: suffix after `_obj.` (e.g. `ac-2_obj.a.1` -> `a.1`).
    if let Some((_, rest)) = part.id.split_once("_obj.") {
        let clean = rest.trim_matches('.').to_ascii_lowercase();
        if !clean.is_empty() {
            return clean;
        }
    }
    // 2. SP 800-171 r3 style: `assessment-objective_DS-A.<sort_id>[.<suffix>]`.
    if !sort_id.is_empty() {
        let stripped = part
            .id
            .strip_prefix("assessment-objective_")
            .unwrap_or(&part.id);
        for prefix in [
            format!("DS-A.{sort_id}"),
            format!("A.{sort_id}"),
            sort_id.to_string(),
        ] {
            if let Some(rest) = stripped.strip_prefix(&prefix) {
                let clean = rest.trim_matches('.').to_ascii_lowercase();
                return if clean.is_empty() {
                    "a".to_string()
                } else {
                    clean
                };
            }
        }
    }
    // 3. Fallback to `label` prop (e.g. `AC-02a.` or `03.01.01[a]` or `a.`).
    let label = prop_value(&part.props, "label", "");
    if !label.is_empty() {
        let id = part_id(&label, sort_id, chain);
        if !id.is_empty() && id != "part" {
            return id;
        }
    }
    if !part.id.is_empty() && part.id != format!("{oscal_id}_obj") {
        if let Some(stripped) = part.id.strip_prefix(oscal_id) {
            let clean = stripped
                .trim_start_matches(['_', '-', '.'])
                .trim_start_matches("obj")
                .trim_start_matches(['_', '-', '.'])
                .to_ascii_lowercase();
            if !clean.is_empty() {
                return clean;
            }
        }
    }
    String::new()
}

fn params_of(ps: &[OscalParam]) -> (BTreeMap<String, Parameter>, HashMap<String, String>) {
    let mut map = BTreeMap::new();
    let mut by_token = HashMap::new();
    let mut used = HashSet::new();
    for p in ps {
        let base = param_key(&p.id);
        let mut key = base.clone();
        let mut n = 2;
        while used.contains(&key) {
            key = format!("{base}_{n}");
            n += 1;
        }
        used.insert(key.clone());
        let label = if !p.label.trim().is_empty() {
            p.label.trim().to_string()
        } else if !p.usage.trim().is_empty() {
            p.usage.trim().to_string()
        } else {
            p.id.clone()
        };
        map.insert(
            key.clone(),
            Parameter {
                label: Some(label),
                value: None,
                extra: BTreeMap::new(),
            },
        );
        by_token.insert(p.id.clone(), key.clone());
        by_token.insert(key.clone(), key.clone());
        for pr in &p.props {
            if pr.name == "alt-identifier" && !pr.value.is_empty() {
                by_token.insert(pr.value.clone(), key.clone());
            }
        }
    }
    (map, by_token)
}

fn inherit_params(ps: &[OscalParam], by_token: &HashMap<String, String>) -> Vec<TokenParam> {
    let mut out = Vec::new();
    let mut seen = HashSet::new();
    let mut add = |token: &str, key: &str, label: &str| {
        if token.is_empty() || key.is_empty() || !seen.insert(token.to_string()) {
            return;
        }
        out.push(TokenParam {
            token: token.to_string(),
            key: key.to_string(),
            label: label.to_string(),
        });
    };
    for p in ps {
        let Some(key) = by_token.get(&p.id) else {
            continue;
        };
        let label = if !p.label.trim().is_empty() {
            p.label.trim()
        } else if !p.usage.trim().is_empty() {
            p.usage.trim()
        } else {
            &p.id
        };
        add(&p.id, key, label);
        for pr in &p.props {
            if pr.name == "alt-identifier" {
                add(&pr.value, key, label);
            }
        }
    }
    out
}

fn flatten_parts<F: FnMut(&str) -> String>(
    items: &[OscalPart],
    chain: &[String],
    sort_id: &str,
    rewrite: &mut F,
    out: &mut Vec<RequirementPart>,
) {
    for item in items {
        if !item.name.is_empty() && item.name != "item" {
            continue;
        }
        let label = prop_value(&item.props, "label", "");
        let id = part_id(&label, sort_id, chain);
        let prose = rewrite(item.prose.trim()).trim().to_string();
        if !prose.is_empty() {
            out.push(RequirementPart {
                id: id.clone(),
                name: None,
                statement: prose,
                extra: BTreeMap::new(),
            });
        }
        let mut next = chain.to_vec();
        next.push(id);
        flatten_parts(&item.parts, &next, sort_id, rewrite, out);
    }
}

fn part_id(label: &str, sort_id: &str, chain: &[String]) -> String {
    let label = label.trim();
    if !sort_id.is_empty() {
        let upper_label = label.to_ascii_uppercase();
        for prefix in [
            format!("SR-{sort_id}."),
            format!("SR-{sort_id}"),
            format!("{sort_id}."),
            sort_id.to_string(),
        ] {
            if upper_label.starts_with(&prefix.to_ascii_uppercase()) && label.len() > prefix.len() {
                let rest = label[prefix.len()..]
                    .trim_start_matches('.')
                    .trim_matches('.');
                if !rest.is_empty() {
                    return rest.to_ascii_lowercase();
                }
            }
        }
    }
    let mut local = label.trim_end_matches('.');
    if local.starts_with('(') && local.ends_with(')') && local.len() >= 2 {
        local = &local[1..local.len() - 1];
    }
    if local.starts_with('[') && local.ends_with(']') && local.len() >= 2 {
        local = &local[1..local.len() - 1];
    }
    let local = local.trim().to_ascii_lowercase();
    let local = if local.is_empty() {
        "part".to_string()
    } else {
        local
    };
    match chain.last() {
        None => local,
        Some(prev) => format!("{prev}.{local}"),
    }
}

fn citations(
    links: &[OscalLink],
    resources: &HashMap<&str, &OscalResource>,
    publisher: &str,
    resolve: Option<&CatalogIndex>,
) -> Vec<ExternalReference> {
    let mut out = Vec::new();
    let mut seen = HashSet::new();
    for lk in links {
        if lk.rel != "reference" {
            continue;
        }
        let Some(res) = resources.get(lk.href.trim_start_matches('#')) else {
            continue;
        };
        if res.title.is_empty() {
            continue;
        }
        if CONTROL_REF_RE.is_match(&res.title) && resolve.is_some() {
            continue;
        }
        let url = res
            .rlinks
            .first()
            .map(|r| r.href.clone())
            .filter(|u| !u.is_empty());
        let key = format!("{}\n{}", res.title, url.as_deref().unwrap_or(""));
        if !seen.insert(key) {
            continue;
        }
        out.push(ExternalReference {
            source: Some(citation_source(&res.title, publisher)),
            description: Some(res.title.clone()),
            url,
            extra: BTreeMap::new(),
        });
    }
    out
}

fn citation_source(title: &str, publisher: &str) -> String {
    let upper = title.to_ascii_uppercase();
    if upper.contains("CFR") {
        "CFR".into()
    } else if upper.starts_with("FIPS")
        || upper.starts_with("SP ")
        || upper.starts_with("IR ")
        || upper.starts_with("NIST")
    {
        "NIST".into()
    } else {
        publisher.into()
    }
}

fn mappings_for(
    item: &CollectedReq,
    self_idx: &CatalogIndex,
    resolve: Option<&CatalogIndex>,
    resources: &HashMap<&str, &OscalResource>,
    families: &HashMap<String, String>,
) -> Result<(Vec<Mapping>, Vec<ExternalReference>), CatalogError> {
    let mut out = Vec::new();
    let mut extra = Vec::new();

    for lk in &item.links {
        match lk.rel.as_str() {
            "reference" => {
                let Some(res) = resources.get(lk.href.trim_start_matches('#')) else {
                    continue;
                };
                let Some(res_idx) = resolve else {
                    continue;
                };
                if !CONTROL_REF_RE.is_match(&res.title) {
                    continue;
                }
                let Some(target) = res_idx.by_zero_padded.get(&res.title) else {
                    return Err(CatalogError::UnresolvedRef(format!(
                        "{} references {}, which is not in {}",
                        item.req.id, res.title, res_idx.framework_id
                    )));
                };
                out.push(new_mapping(
                    &item.req,
                    &target.id,
                    "",
                    Relationship::IntersectsWith,
                    "Imported from an OSCAL reference link. NIST cites this SP 800-53 control from the requirement. The set relationship is unreviewed.",
                ));
            }
            "incorporated-into" | "incorporated_into" => {
                match resolve_href(&lk.href, self_idx, families)? {
                    HrefTarget::Family(title) => extra.push(family_ref(&lk.rel, &title)),
                    HrefTarget::Req(target, part) => out.push(new_mapping(
                        &item.req,
                        &target,
                        &part,
                        Relationship::SubsetOf,
                        "Imported from an OSCAL incorporated-into link. NIST records the source requirement as incorporated into the target.",
                    )),
                }
            }
            "moved-to" => match resolve_href(&lk.href, self_idx, families)? {
                HrefTarget::Family(title) => extra.push(family_ref(&lk.rel, &title)),
                HrefTarget::Req(target, part) => out.push(new_mapping(
                    &item.req,
                    &target,
                    &part,
                    Relationship::EquivalentTo,
                    "Imported from an OSCAL moved-to link. NIST records the source requirement as moved to the target.",
                )),
            },
            "addressed_by" => match resolve_href(&lk.href, self_idx, families)? {
                HrefTarget::Family(title) => extra.push(family_ref(&lk.rel, &title)),
                HrefTarget::Req(target, part) => out.push(new_mapping(
                    &item.req,
                    &target,
                    &part,
                    Relationship::IntersectsWith,
                    "Imported from an OSCAL addressed-by link. NIST records the source requirement as addressed by the target.",
                )),
            },
            _ => {}
        }
    }
    Ok((out, extra))
}

fn family_ref(rel: &str, title: &str) -> ExternalReference {
    ExternalReference {
        source: Some("NIST".into()),
        description: Some(format!(
            "OSCAL {rel} link points at the {title} family rather than a single requirement."
        )),
        url: None,
        extra: BTreeMap::new(),
    }
}

fn new_mapping(
    req: &Requirement,
    target_id: &str,
    part: &str,
    relationship: Relationship,
    summary: &str,
) -> Mapping {
    let mut target_ref = target_id.to_string();
    let mut id_rest = format!(
        "{}_to_{}",
        req.id.trim_start_matches("requirement--"),
        target_id.trim_start_matches("requirement--")
    );
    if !part.is_empty() {
        target_ref = format!("{target_id}#{part}");
        id_rest.push_str("_part_");
        id_rest.push_str(&part.replace('.', "-"));
    }
    Mapping {
        object_type: "mapping".into(),
        id: format!("mapping--{id_rest}"),
        spec_version: SPEC_VERSION.into(),
        created: req.created,
        modified: req.modified,
        name: None,
        revoked: None,
        created_by_ref: None,
        tags: None,
        external_references: None,
        extensions: None,
        lang: None,
        source_ref: req.id.clone(),
        target_ref,
        relationship,
        rationale: Some(Rationale::Semantic),
        review_status: Some(ReviewStatus::Draft),
        confidence: Some(Confidence::Low),
        summary: Some(summary.to_string()),
        parameter_map: None,
        combined_with_refs: None,
        extra: BTreeMap::new(),
    }
}

enum HrefTarget {
    Req(String, String),
    Family(String),
}

fn resolve_href(
    href: &str,
    idx: &CatalogIndex,
    families: &HashMap<String, String>,
) -> Result<HrefTarget, CatalogError> {
    if let Some(caps) = PART_HREF_RE.captures(href) {
        let Some(target) = idx.by_oscal_id.get(&caps[1]) else {
            return Err(CatalogError::UnresolvedRef(format!(
                "link {href} does not match a control"
            )));
        };
        if !target.parts.contains(&caps[2]) {
            return Err(CatalogError::UnresolvedRef(format!(
                "link {href} does not match a statement part"
            )));
        }
        return Ok(HrefTarget::Req(target.id.clone(), caps[2].to_string()));
    }
    if let Some(caps) = HASH_HREF_RE.captures(href) {
        if let Some(target) = idx.by_oscal_id.get(&caps[1]) {
            return Ok(HrefTarget::Req(target.id.clone(), String::new()));
        }
        if let Some(title) = families.get(&caps[1]) {
            let label = if title.is_empty() {
                caps[1].to_ascii_uppercase()
            } else {
                title.clone()
            };
            return Ok(HrefTarget::Family(label));
        }
        return Err(CatalogError::UnresolvedRef(format!(
            "link {href} does not match a control"
        )));
    }
    let bare = href.trim_start_matches('#');
    if let Some(target) = idx.by_sort_id.get(bare) {
        return Ok(HrefTarget::Req(target.id.clone(), String::new()));
    }
    if let Some(target) = idx.by_oscal_id.get(bare) {
        return Ok(HrefTarget::Req(target.id.clone(), String::new()));
    }
    Err(CatalogError::UnresolvedRef(format!(
        "link {href} does not match a control"
    )))
}

fn build_index(framework_id: &str, items: &[CollectedReq]) -> CatalogIndex {
    let mut by_oscal_id = HashMap::new();
    let mut by_sort_id = HashMap::new();
    let mut by_zero_padded = HashMap::new();
    for item in items {
        let parts: HashSet<String> = item
            .req
            .parts
            .as_deref()
            .unwrap_or(&[])
            .iter()
            .map(|p| p.id.clone())
            .collect();
        let entry = IndexRef {
            id: item.req.id.clone(),
            parts,
        };
        by_oscal_id.insert(item.oscal_id.clone(), entry.clone());
        if !item.sort_id.is_empty() {
            by_sort_id.insert(item.sort_id.clone(), entry.clone());
        }
        if !item.zero_pad.is_empty() {
            by_zero_padded.insert(item.zero_pad.clone(), entry);
        }
    }
    CatalogIndex {
        framework_id: framework_id.to_string(),
        by_oscal_id,
        by_sort_id,
        by_zero_padded,
    }
}

fn prop_value(props: &[OscalProp], name: &str, class: &str) -> String {
    let mut fallback = String::new();
    for p in props {
        if p.name != name {
            continue;
        }
        if class.is_empty() && p.class.is_empty() {
            return p.value.clone();
        }
        if !class.is_empty() && p.class == class {
            return p.value.clone();
        }
        if fallback.is_empty() && class.is_empty() {
            fallback = p.value.clone();
        }
    }
    if class.is_empty() {
        fallback
    } else {
        String::new()
    }
}

fn display_id(props: &[OscalProp], sort_id: &str, oscal_id: &str) -> String {
    let unlabeled = props
        .iter()
        .find(|p| p.name == "label" && p.class.is_empty())
        .map(|p| p.value.as_str())
        .unwrap_or("");
    if CONTROL_DISPLAY_RE.is_match(unlabeled) {
        return unlabeled.to_string();
    }
    if !sort_id.is_empty() {
        return sort_id.to_string();
    }
    let zp = prop_value(props, "label", "zero-padded");
    if !zp.is_empty() {
        return zp;
    }
    if !unlabeled.is_empty() {
        return unlabeled.to_string();
    }
    oscal_id.to_string()
}

fn slug(s: &str) -> String {
    let mut out = String::new();
    let mut prev_sep = false;
    for ch in s.to_ascii_lowercase().chars() {
        if ch.is_ascii_lowercase() || ch.is_ascii_digit() {
            out.push(ch);
            prev_sep = false;
        } else if !prev_sep {
            out.push('-');
            prev_sep = true;
        }
    }
    out.trim_matches('-').to_string()
}

fn param_key(id: &str) -> String {
    let mut out = String::new();
    let mut prev_sep = false;
    for ch in id.to_ascii_lowercase().chars() {
        if ch.is_ascii_lowercase() || ch.is_ascii_digit() {
            out.push(ch);
            prev_sep = false;
        } else if !prev_sep {
            out.push('_');
            prev_sep = true;
        }
    }
    out.trim_matches('_').to_string()
}
